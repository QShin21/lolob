def p(text): return '<p>' + text + '</p>'
def steps(*items): return '<ol>' + ''.join('<li>'+x+'</li>' for x in items) + '</ol>'
def bullets(*items): return '<ul>' + ''.join('<li>'+x+'</li>' for x in items) + '</ul>'
def box(title, text): return '<aside class="note"><b>'+title+'</b>'+p(text)+'</aside>'
def table(head, rows): return '<table><thead><tr>'+''.join('<th>'+x+'</th>' for x in head)+'</tr></thead><tbody>'+''.join('<tr>'+''.join('<td>'+x+'</td>' for x in row)+'</tr>' for row in rows)+'</tbody></table>'
def fig(name, caption, cls=''):
    raw = (OUT / 'images' / (name+'.png')).read_bytes()
    src = 'data:image/png;base64,'+base64.b64encode(raw).decode()
    return f'<figure class="{cls}"><a href="#" onclick="showImage(this.querySelector(\'img\'));return false" title="点击查看原图"><img src="{src}" alt="{html.escape(caption)}"></a><figcaption>{caption}</figcaption></figure>'
def page(title, lead, body, group='操作指南'):
    pages.append(dict(title=title, lead=lead, body=body, group=group))

