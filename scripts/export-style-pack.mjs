import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { tsImport } from 'tsx/esm/api';
const { builtinStyleArchive } = await tsImport('../server/style-packs.ts', import.meta.url);
const { BUILTIN_RUNTIME_STYLES, BUILTIN_STYLE_REF } = await tsImport('../shared/style-packs.ts', import.meta.url);
const selected = process.argv[3] ? BUILTIN_RUNTIME_STYLES.find(p => p.id === process.argv[3]) : BUILTIN_STYLE_REF;
if (!selected) throw new Error('Unknown built-in style id');
const destination = path.resolve(process.argv[2] || 'verification-output/glacier-aurora.riftstyle.zip');
await mkdir(path.dirname(destination), { recursive: true });
await writeFile(destination, builtinStyleArchive(selected));
console.log(destination);
